    /**
     * ตรวจสอบว่าซีนนี้เป็นมินิเกมหรือไม่
     */
    public static boolean isMiniGameScene(String sceneName) {
        return sceneName != null && 
               (sceneName.contains("MINIGAME_MATCH") || 
                sceneName.contains("MINIGAME_RPS"));
    }
    
    /**
     * ดึงประเภทมินิเกมจากชื่อซีน
     */
    public static String getMiniGameType(String sceneName) {
        if (sceneName == null) return "";
        if (sceneName.contains("MATCH")) return "MATCH";
        if (sceneName.contains("RPS")) return "RPS";
        return "";
    }
    
